"""Rebuild the synthetic fixtures and record their real SHA-256 values in specs.json.

Everything written here is FICTIONAL. Sample hashes are SHA-256 digests of
descriptive strings, not of any file. The capa-shaped reports, recovery records
and label lists are hand-written to exercise the pipeline; they are not tool
output and say nothing about real malware.

Run from the project root:  python tools/build_fixtures.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline.synthetic import NOTE, dumps, fake_sha, scenario_files  # noqa: E402

FIX = ROOT / "fixtures"


def write(path: Path, obj) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = dumps(obj)
    path.write_bytes(data)
    return hashlib.sha256(data).hexdigest()


def build() -> list[dict]:
    specs = []

    # Sample 1: the guide's worked example; gate accepts.
    s1 = fake_sha("SYNTH-001 fictional packed sample (not a real file)")
    p1 = fake_sha("SYNTH-001 fictional recovered payload (not a real file)")
    files1 = scenario_files("accepted", s1, p1)

    # Sample 2: gate rejects (V4 fails, budget 25 > 20). B is supplied but must not be used.
    s2 = fake_sha("SYNTH-002 fictional packed sample (not a real file)")
    p2 = fake_sha("SYNTH-002 fictional recovered payload (not a real file)")
    files2 = scenario_files("rejected", s2, p2)

    for label, sha, folder, files in (("SYNTH-001", s1, "sample_001", files1),
                                      ("SYNTH-002", s2, "sample_002", files2)):
        inputs, hashes = {}, {}
        for key, (name, obj) in files.items():
            rel = f"{folder}/{name}"
            hashes[key] = write(FIX / rel, obj)
            inputs[key] = rel
        specs.append({"label": label, "sha256": sha, "mode": "synthetic", "approval_id": None,
                      "inputs": inputs, "input_sha256": hashes})

    mapping_rows = [
        ("T1027", "current", ""), ("T1055", "current", ""), ("T1055.001", "current", ""),
        ("T1082", "current", ""), ("T1105", "current", ""), ("T1112", "current", ""),
        ("T1486", "current", ""), ("T1497", "current", ""), ("T1620", "current", ""),
        ("T0001", "revoked", "T1027"),
    ]
    lines = ["technique_id,status,replacement,note"]
    lines += [f"{t},{s},{r},synthetic fixture row" for t, s, r in mapping_rows]
    (FIX / "attack_map.csv").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))

    (FIX / "specs.json").write_bytes((json.dumps(specs, indent=2) + "\n").encode("utf-8"))
    (FIX / "README.md").write_text(
        "# Synthetic fixtures\n\nEverything in this folder is fictional and generated by "
        "`tools/build_fixtures.py`.\nSample hashes are digests of labels, not of files. "
        "No real tool output, sample or payload is stored here.\n\n"
        "`attack_map.csv` is a fictional mapping table (T0001 is a made-up revoked ID that maps to T1027);\n"
        "it is **not** the official ATT&CK export. Edit the generator, not the files, then rerun it so\n"
        "the hashes in `specs.json` stay correct.\n",
        encoding="utf-8", newline="\n",
    )
    return specs


if __name__ == "__main__":
    for s in build():
        print(f"{s['label']}: {s['sha256']}  ({len(s['inputs'])} inputs hashed)")
    print(f"fixtures written to {FIX}")
